/**
 * =============================================================================
 *  치수 재기 — 두 점 사이가 몇 m 인가
 * =============================================================================
 *  배치 에디터인데 **거리를 잴 길이 없었다.** 통로 폭이 3m 인지 4m 인지, 설비
 *  사이가 카트가 지나갈 만한지를 확인하려면 눈대중밖에 없었다. 그런데 그건 이
 *  도구가 늘 하는 이야기의 한복판이다 — 카트 경로가 포트 **정면 1m 안**을
 *  지나야 정차역이 되고, 선반 앞 구역도 폭이 정해져 있다.
 *
 *  ── 왜 도면에 안 남기나 ───────────────────────────────────────────────────
 *  잰 것은 **도면이 아니다.** 자를 대 보는 일은 그리는 동안의 손놀림이지 결과가
 *  아니므로, 저장하지도(`DOC_KEYS` 밖) 되돌리기에 쌓지도 않는다. 남기고 싶은
 *  치수는 구역을 그리거나 벽을 세워서 남기는 것이 맞다.
 *
 *  ── 가로·세로를 따로 말한다 ──────────────────────────────────────────────
 *  「4.24m」 만 보여 주면 비스듬한 두 점 사이에서 쓸모가 적다. 실제로 알고 싶은
 *  것은 대개 **축에 붙은 치수**다 — 「가로 3.0 · 세로 3.0」 이어야 통로가 몇 m
 *  인지 답이 된다. 그래서 셋을 함께 낸다.
 * ---------------------------------------------------------------------------
 */

/** 이보다 짧으면 같은 자리를 두 번 누른 것으로 본다 (m) */
export const MIN_SPAN = 0.05;

const n = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0);

/**
 * 두 점 사이.
 *  @param a [x, z] · @param b [x, z]  (바닥 평면은 XZ 다 — y 는 높이)
 *  @returns null 이면 잴 것이 없다(점이 없거나 같은 자리)
 */
export function measureOf(a, b) {
  if (!a || !b) return null;
  const dx = n(b[0]) - n(a[0]);
  const dz = n(b[1]) - n(a[1]);
  const dist = Math.hypot(dx, dz);
  if (!(dist >= MIN_SPAN)) return null;
  return {
    dist,
    dx: Math.abs(dx),
    dz: Math.abs(dz),
    /** +X 를 0° 로 둔 방위 (0~180). 반대로 그어도 같은 값이라 뒤집히지 않는다 */
    deg: ((Math.atan2(dz, dx) * 180) / Math.PI + 180) % 180,
    mid: [(n(a[0]) + n(b[0])) / 2, (n(a[1]) + n(b[1])) / 2],
  };
}

/**
 * 사람이 읽는 길이.
 *  10m 를 넘으면 소수 첫째 자리로 충분하다 — 12.34m 는 읽는 데 방해만 되고,
 *  그 정확도를 믿을 만큼 클릭이 정밀하지도 않다.
 */
export const spanText = (m) => {
  if (!Number.isFinite(m)) return '—';
  return m >= 10 ? `${m.toFixed(1)} m` : `${m.toFixed(2)} m`;
};

/** 「3.00 m · 가로 3.00 · 세로 0.00」 — 축에 붙은 치수를 함께 말한다 */
export function measureText(mm) {
  if (!mm) return '';
  return `${spanText(mm.dist)} · 가로 ${spanText(mm.dx)} · 세로 ${spanText(mm.dz)}`;
}

/**
 * 다음 클릭이 무엇을 하는가 — 리듀서와 화면이 **같은 규칙**을 봐야 한다.
 * ---------------------------------------------------------------------------
 *  첫 점 → 둘째 점 → (셋째 클릭은) 다시 처음. 「지우고 다시」 버튼을 따로 두면
 *  자를 옮길 때마다 두 번 눌러야 한다.
 *
 *  @returns 다음 상태. `null` 이면 아무것도 없는 처음
 */
export function nextMeasure(cur, point) {
  if (!point) return null;
  if (!cur?.a) return { a: point, b: null };
  if (!cur.b) {
    /* 같은 자리를 두 번 누르면 재는 것이 없다 — 첫 점을 그리로 옮긴다 */
    return measureOf(cur.a, point) ? { a: cur.a, b: point } : { a: point, b: null };
  }
  return { a: point, b: null };
}
