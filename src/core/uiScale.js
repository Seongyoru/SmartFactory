/**
 * 화면 배율 — **글자·단추·여백을 통째로** 키우고 줄인다.
 * ---------------------------------------------------------------------------
 *  4K 모니터를 OS 배율 100% 로 쓰면 CSS 폭이 3840 이 된다. 27" FHD 와 견주면
 *  같은 12px 글자가 **물리적으로 절반**이라 읽을 수가 없다. 거꾸로 1366×768
 *  노트북에서는 툴바와 패널이 자리를 다 먹는다.
 *
 *  치수 372곳을 `rem` 으로 바꾸는 길도 있었지만, 그러면 글자만 커지고 여백과
 *  아이콘은 그대로라 **간격이 무너진다**. CSS `zoom` 은 레이아웃 전체를 같은
 *  비율로 다시 흘려서, 창이 그만큼 작아진 것과 똑같이 동작한다.
 *
 *  **자동으로 정하지 않는다.** 브라우저는 화면의 실제 크기(인치)를 모른다 —
 *  3840px 이 32" 인지 15" 노트북의 고해상도 화면인지 구분할 방법이 없고,
 *  OS 배율이 이미 150% 라면 여기서 또 키우는 순간 글자가 두 배가 된다.
 *  그래서 고르는 것은 사람 몫으로 남긴다.
 * ---------------------------------------------------------------------------
 */

/** 고를 수 있는 배율. 1 이 반드시 들어 있어야 한다 — 되돌릴 자리다 */
export const UI_SCALES = [0.8, 0.9, 1, 1.15, 1.3, 1.5, 1.75, 2];

export const DEFAULT_UI_SCALE = 1;

/**
 * 아무 값이나 들어와도 **목록 안의 값**으로 만든다.
 *  저장된 값은 사람이 손댈 수 있는 localStorage 에서 온다. 0 이나 문자열이
 *  들어오면 `zoom: 0` 이 되어 화면이 사라진다 — 그 길을 막는다.
 */
export const clampUiScale = (v) => {
  const n = Number(v);
  if (!Number.isFinite(n)) return DEFAULT_UI_SCALE;
  /* 가장 가까운 눈금으로 붙인다. 목록에 없는 1.05 도 화면은 멀쩡하지만,
     고르는 칸에서 **아무것도 안 골라진 것처럼** 보여 되돌릴 수가 없다. */
  return UI_SCALES.reduce((best, s) =>
    Math.abs(s - n) < Math.abs(best - n) ? s : best, DEFAULT_UI_SCALE);
};

/** 「130%」 처럼 사람이 읽는 꼴 */
export const uiScaleLabel = (s) => `${Math.round(s * 100)}%`;

/**
 * 이 칸에 걸려 있는 **실제 배율**.
 * ---------------------------------------------------------------------------
 *  `zoom` 아래에서는 재는 방법마다 답이 다르다.
 *    getBoundingClientRect · clientX/clientY → 배율이 **곱해진** 바깥 좌표
 *    offsetWidth · style 로 넣는 px          → 배율이 **안 곱해진** 안쪽 좌표
 *  둘을 섞어 쓰면 배율이 한 번 더 곱해지거나 나뉜다. 그래서 재는 칸 자신에게
 *  물어본다 — 배율을 어디에 걸었는지(루트인지 중간인지) 몰라도 맞는다.
 *
 *  못 재면 1 이다. 배율이 없다고 보는 쪽이, 0 으로 나눠 NaN 을 만드는 것보다
 *  훨씬 덜 나쁘다 — 배율 1 인 사람은 어차피 대부분이다.
 */
export const zoomOf = (el) => {
  const inner = el?.offsetWidth ?? 0;
  if (!inner) return 1;
  const outer = el.getBoundingClientRect?.().width ?? 0;
  const z = outer / inner;
  return Number.isFinite(z) && z > 0 ? z : 1;
};
