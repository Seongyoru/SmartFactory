/**
 * =============================================================================
 *  닿는가 — 이 설비가 만든 것이 저 자리까지 갈 수 있나
 * =============================================================================
 *  디스패칭 규칙(`dispatch.js`)이 오더를 읽어 다음 품종을 고른다. 그런데 오더를
 *  **종류만으로** 읽으면, 그 종류를 만드는 설비가 전부 끌려간다 — 산출이 오더의
 *  목적지에 **닿든 말든.**
 *
 *  실제로 잰 값이다. 제작기 A 는 적치대로, 제작기 B 는 조립기로 보내는 도면에서
 *  「제작품 2 를 적치대로 1000개」 오더를 걸었더니:
 *
 *      차례대로       조립품 93개   적치대 도착 96
 *      밀린 것 먼저    조립품  0개   적치대 도착 192
 *
 *  조립기가 굶어 **라인이 통째로 섰다.** 제작기 B 가 제작품 2 를 아무리 만들어도
 *  그 오더의 진척은 한 톨도 안 오르는데(반사실로 확인했다 — B 를 놓아 주어도
 *  적치대 도착은 192 그대로였다) 규칙만 B 를 끌고 간 것이다.
 *
 *  ── **모르면 닿는 것으로 본다** ──────────────────────────────────────────
 *  이 방향이 취향이 아니라 필수다. 반대로 짜면(모르면 안 닿는 것으로) 카트로만
 *  대는 멀쩡한 라인이 조용히 「차례대로」가 되는데, **아무 검사도 안 터진다.**
 *  틀리는 쪽을 고를 수 있다면 「덜 걸러내는 쪽」으로 틀려야 한다 — 지금까지
 *  하던 대로 도는 것이 최악이고, 안 도는 것은 그보다 나쁘다.
 *
 *  그래서 **확실히 안 닿는 것만** 걸러낸다:
 *      · 카트가 한 대라도 있으면  → 전부 닿는 것으로 본다(카트 길은 안 따라간다)
 *      · 끝이 안 물린 벨트가 있으면 → 그 설비는 닿는 것으로 본다
 *      · 그 밖에는 벨트를 따라가 본다
 * ---------------------------------------------------------------------------
 */

/**
 * @param d.links 도면의 연결 전부
 * @param d.carts 도면의 카트 전부
 * @returns (설비 uid, 목적지 uid) => 닿을 수 있는가
 */
export function reachOf(d = {}) {
  const links = d.links ?? [];
  const carts = d.carts ?? [];

  /* 카트는 길을 여기서 못 따라간다 — 있으면 전부 닿는 것으로 본다 */
  if (carts.length) return () => true;

  /** 설비 → 그 설비가 보내는 곳들 */
  const next = new Map();
  /** 나가는 길 중 **어디로 가는지 모르는 것**이 있는 설비 */
  const murky = new Set();

  for (const l of links) {
    const a = l?.from?.uid;
    if (!a) continue;
    const b = l?.to?.uid;
    if (!b) { murky.add(a); continue; }      // 끝이 어디에도 안 물렸다
    if (!next.has(a)) next.set(a, new Set());
    next.get(a).add(b);
  }

  return (from, to) => {
    if (!from || !to || from === to) return true;
    const seen = new Set([from]);
    const queue = [from];
    /**
     * 걸음 수를 묶어 둔다 — `seen` 이 순환을 막지만, 그 그물이 언젠가 찢어지면
     * **검사가 실패하는 게 아니라 멈춘다**(실제로 겪었다). 멈추는 것보다는
     * 「모르겠다」가 낫고, 모르면 이 파일의 방향대로 **닿는 것으로** 답한다.
     */
    let steps = 0;
    const cap = links.length + 2;
    while (queue.length) {
      if (++steps > cap) return true;
      const cur = queue.shift();
      /* 여기서부터는 어디로 가는지 모른다 — 닿는 것으로 본다 */
      if (murky.has(cur)) return true;
      for (const n of next.get(cur) ?? []) {
        if (n === to) return true;
        if (!seen.has(n)) { seen.add(n); queue.push(n); }   // 순환은 seen 이 막는다
      }
    }
    return false;
  };
}
