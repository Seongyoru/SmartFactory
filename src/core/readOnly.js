/**
 * =============================================================================
 *  보기 전용 — 고치지 않고 보기만 한다
 * =============================================================================
 *  휴대폰이나 남에게 화면을 넘길 때, 편집 UI 를 좁은 화면에 욱여넣는 것보다
 *  **볼 수 있는 것을 제대로 보여 주는** 편이 낫다. 손가락으로 도면을 밀다가
 *  설비가 딸려 가는 사고도 여기서 사라진다.
 *
 *  ── 화면을 감추는 것은 막는 것이 아니다 ─────────────────────────────────
 *  단추를 안 그려도 단축키는 window 에 그대로 붙어 있고, 좁은 화면의 패널은
 *  `display:none` 일 뿐이라 그 안의 입력칸은 살아 있다. 그래서 **진짜 방어선은
 *  리듀서 한 겹**이다. `dispatch` 는 store 한 곳에서만 나오고 코어 모듈 어디에도
 *  dispatch 호출이 없으므로, 여기를 막으면 툴바·인스펙터·캔버스·단축키·구역
 *  목록·오더가 **전부** 걸린다. 감추는 일은 소음을 줄이는 데만 쓴다.
 *
 *  ── 막을 것을 이름으로 적지 않는다 ──────────────────────────────────────
 *  도면을 바꾸는 액션은 서른 개가 넘고, `SET` 은 만능이라 벨트 속도 슬라이더
 *  하나가 그 목록을 그냥 뚫는다. 그래서 **리듀서를 한 번 돌려 보고 도면이
 *  실제로 바뀌었는지**로 판정한다 — 되돌리기가 이미 쓰는 그 근거다. 액션이
 *  새로 늘어도 여기를 고칠 일이 없다.
 *
 *  ── 그런데 세 가지는 도면을 바꿔도 통과시켜야 한다 ──────────────────────
 *  이걸 빠뜨리면 앱이 조용히 망가진다. 하나씩 이유가 다르다.
 * ---------------------------------------------------------------------------
 */

/**
 * 도면을 바꾸더라도 보기 전용에서 **통과시키는** 것들.
 *
 *  `LOAD_LAYOUT`  — 「무엇을 보고 있는가」 를 바꾸는 것이지 고치는 것이 아니다.
 *      공용 도면을 여는 길이고, **부팅 복원도 이걸 쓴다** — 막으면 새로고침할
 *      때마다 빈 도면이 뜬다.
 *  `ADD_LIB_ITEM` — 막으면 **사용자 GLB 가 영영 안 돌아온다.** 부팅 때
 *      EditorProvider 자신이 IndexedDB 에서 되살리며 이걸 쏜다. 「사람이 누른
 *      것」 이 아니라 「앱이 제자리를 찾는 것」 이다.
 *
 *  손에 든 것을 놓는 일은 여기 없다 — `SET_TOOL` 이 이미 초안을 다 비우고,
 *  도구는 도면이 아니라서 애초에 이 검문을 안 거친다.
 */
export const ALWAYS_OK = ['LOAD_LAYOUT', 'ADD_LIB_ITEM'];

/**
 * 구역 **감추기**는 보기 기능이다 — 도면을 바꾸는데도.
 * ---------------------------------------------------------------------------
 *  구역 목록의 눈 아이콘은 `UPDATE_ZONE { hidden }` 을 쏜다. zones 는 도면이라
 *  위의 판정에 그대로 걸리는데, 그러면 「보기 전용인데 가리는 것을 못 치운다」 가
 *  된다 — 보려고 켠 모드에서 보는 기능이 줄어든다.
 *
 *  **`hidden` 만 든 패치일 때만** 통과시킨다. 같은 액션으로 이름이나 색을
 *  같이 보내면 그건 편집이다.
 */
export const isZoneHide = (action) =>
  action?.type === 'UPDATE_ZONE'
  && !!action.patch
  && Object.keys(action.patch).length === 1
  && Object.prototype.hasOwnProperty.call(action.patch, 'hidden');

/**
 * 이 액션을 보기 전용에서 **그냥 흘려보내도 되는가**.
 *  @param action  들어온 액션
 *  @returns true 면 도면이 바뀌든 말든 통과
 */
export const isAllowed = (action) =>
  ALWAYS_OK.includes(action?.type) || isZoneHide(action);

/**
 * 리듀서 한 겹.
 * ---------------------------------------------------------------------------
 *  @param base    감쌀 리듀서 (여기서는 historyReducer)
 *  @param sameDoc 도면이 같은가 — store 가 되돌리기에 쓰는 그 함수를 그대로 받는다
 *  @param docOf   상태에서 도면만 떼는 함수 — 역시 store 것을 그대로 받는다
 *
 *  **모듈을 가로질러 값을 베끼지 않으려고 함수로 받는다.** 여기서 DOC_KEYS 를
 *  다시 적으면 store 쪽이 늘어날 때 조용히 어긋난다 — 그때 새 필드는 보기
 *  전용에서 **고쳐진다.**
 */
export function withReadOnly(base, { sameDoc, docOf }) {
  return (state, action) => {
    const next = base(state, action);
    if (!state?.readOnly) return next;
    if (isAllowed(action)) return next;
    /* 도면이 그대로면 보기값만 바뀐 것이다 — 고르기·뷰 전환·탭·배율 전부 여기로 */
    if (sameDoc(docOf(state), docOf(next))) return next;
    /* **바뀐 것을 버린다.** 상태를 그대로 돌려주므로 화면도 그대로다 */
    return state;
  };
}
