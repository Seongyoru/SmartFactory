/**
 * =============================================================================
 *  흔들림의 **모양** — 확률 분포
 * =============================================================================
 *  이 도구는 이미 여러 판을 돌려 평균과 신뢰구간을 내고, Welch 로 「정말 다른가」
 *  까지 답한다(`core/replicate.js`). 그런데 **입력이 균등분포 하나뿐**이었다.
 *  그러면 그 통계가 반쪽이다 — 나오는 ± 는 「이 배치가 얼마나 흔들리나」가 아니라
 *  「내가 균등분포를 가정했을 때 얼마나 흔들리나」이기 때문이다.
 *
 *  ── 모양이 무엇을 바꾸는가 — **재 보고 적는다** ──────────────────────────
 *  처음에는 「꼬리 없는 분포로 돌리면 버퍼를 실제보다 작게 잡게 된다」고 적었다.
 *  **재 보니 틀렸다.** 같은 ± 를 주면 균등이 **제일 크게** 흔들린다 — 가장자리
 *  값이 가운데만큼 자주 나오기 때문이다.
 *
 *  버퍼 8칸짜리 라인을 30분 × 20판 돌려 잰 값이다.
 *
 *      모양        평균 막힘   가장 나쁜 판   한 개 최대배수   배수의 sd
 *      고르게        79초        96초          1.50배         0.289
 *      가운데로      58초        75초          2.03배         0.251
 *      가끔 길게     55초        71초          2.68배         0.251
 *      최소·보통·최대 45초        61초          1.50배         0.204
 *
 *  **막힘은 꼬리가 아니라 흔들림의 크기(sd)를 따라간다.** 꼬리는 다른 자리에
 *  나타난다 — 「한 개가 얼마나 늦을 수 있나」다. 균등은 ±50% 면 1.50배가
 *  천장이지만 로그정규는 **2.68배**가 나온다. 평균이 아니라 **드문 사고**로
 *  드러나는 값이라, 안전 재고나 납기 약속을 잡을 때 갈린다.
 *
 *  그러니 고르는 기준은 이렇다.
 *
 *      「±안에서 아무 값이나 나온다」        → 고르게
 *      「대개 비슷한데 드물게 크게 늦는다」  → 가끔 길게   ← 대개 이쪽이 현실이다
 *      「최소·보통·최대만 안다」             → 최소·보통·최대
 *
 *  ── 넷만 둔다 ─────────────────────────────────────────────────────────────
 *  상용 도구는 스무 가지씩 갖고 있지만, 대부분은 데이터를 피팅해 쓰는 것이고
 *  이 도구는 아직 실적 데이터를 안 받는다. **손으로 고르는 상황에서 뜻이 갈리는
 *  것 넷**이면 충분하다.
 *
 *      고르게      균등    꼬리가 없다 — 지금까지의 기본값
 *      가운데로    정규    대칭. 가운데가 흔하고 양끝이 드물다
 *      가끔 길게   로그정규 오른쪽 꼬리 — **공정·수리 시간의 현실**
 *      최소·보통·최대  삼각  데이터가 없을 때 전문가 추정으로 쓰는 표준
 *
 *  ── **평균은 넷 다 1 이다** ───────────────────────────────────────────────
 *  이것이 이 모듈에서 가장 중요한 성질이다. 모양을 바꿔도 평균이 그대로라
 *  **라인의 천장(`balance.js`)이 안 움직인다.** 달라지는 것은 흔들림뿐이다.
 *
 *  안 그러면 「분포를 바꿨더니 천장이 바뀌었다」가 되고, 그러면 두 배치를 견줄
 *  때 배치 차이인지 분포 차이인지 알 수 없어진다 — 이 도구가 하려는 일이
 *  통째로 무너진다.
 *
 *  (정규만 **아주 조금** 어긋난다. 0.05 아래로는 자르기 때문이다. 편차를
 *  크게 줄수록 평균이 미세하게 올라가는데, 검사가 그 폭을 지켜본다.)
 * ---------------------------------------------------------------------------
 */

/** 배수가 이보다 작아지지 않게 자른다 — 0 이나 음수 시간은 뜻이 없다 */
export const MIN_MULT = 0.05;

/**
 * 고를 수 있는 모양들. **id 는 도면에 저장되므로 바꾸지 말 것.**
 *  `label` 은 「무슨 분포인가」가 아니라 **「무슨 일이 벌어지나」**로 적는다 —
 *  로그정규를 아는 사람만 쓰는 도구가 아니다.
 */
export const SHAPES = [
  {
    id: 'flat',
    label: '고르게',
    stat: '균등',
    why: '±안에서 아무 값이나 똑같이 — **같은 ± 면 제일 크게 흔들립니다**',
  },
  {
    id: 'bell',
    label: '가운데로',
    stat: '정규',
    why: '가운데가 흔하고 양끝이 드뭅니다 — 대칭',
  },
  {
    id: 'tail',
    label: '가끔 길게',
    stat: '로그정규',
    why: '대개 비슷한데 **드물게 몇 배로 늦습니다** — 공정·수리 시간의 현실',
  },
  {
    id: 'peak',
    label: '최소·보통·최대',
    stat: '삼각',
    why: '보통값이 제일 흔합니다 — 넷 중 **가장 얌전합니다**',
  },
];

/** 저장된 값 → 아는 모양 (모르면 예전 그대로) */
export const DEFAULT_SHAPE = 'flat';
export const shapeOf = (v) => (SHAPES.some((s) => s.id === v) ? v : DEFAULT_SHAPE);
export const shapeInfo = (v) => SHAPES.find((s) => s.id === shapeOf(v)) ?? SHAPES[0];

/**
 * 표준정규 한 개 (Box–Muller).
 *  난수를 **두 개** 먹는다 — 씨앗을 고정하면 여전히 같은 값이 나오므로
 *  반복 실행의 재현성에는 영향이 없다.
 */
function normal(rand) {
  const u = Math.max(1e-12, rand());
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rand());
}

/**
 * **1 을 중심으로 흔들리는 배수**를 하나 뽑는다.
 *
 *  @param ratio  퍼짐 (0 ~ 1). 0 이면 흔들림 없이 정확히 1
 *  @param shape  `SHAPES` 의 id
 *  @returns 평균 1 인 양수 배수
 */
export function drawShape(ratio = 0, rand = Math.random, shape = DEFAULT_SHAPE) {
  const r = Math.max(0, ratio || 0);
  if (!(r > 0)) return 1;

  switch (shapeOf(shape)) {
    case 'bell': {
      /* ± 를 **2σ** 로 읽는다 — 대충 그 범위 안에 95% 가 들어온다.
         고르게(±r 이 곧 경계)와 눈금이 맞아, 모양만 바꿔도 폭이 비슷하다. */
      return Math.max(MIN_MULT, 1 + (r / 2) * normal(rand));
    }
    case 'tail': {
      /* 로그정규 — **평균이 정확히 1** 이 되도록 μ 를 내려 잡는다.
         c(변동계수)를 정규와 같은 r/2 로 두어 폭을 맞춘다. */
      const c = r / 2;
      const s2 = Math.log(1 + c * c);
      return Math.max(MIN_MULT, Math.exp(-s2 / 2 + Math.sqrt(s2) * normal(rand)));
    }
    case 'peak': {
      /* 삼각 (1−r, 1, 1+r) — 좌우 대칭이라 평균이 정확히 1 이다 */
      const u = rand();
      return Math.max(MIN_MULT, u < 0.5
        ? 1 - r + r * Math.sqrt(2 * u)
        : 1 + r - r * Math.sqrt(2 * (1 - u)));
    }
    default:
      /* 고르게 — 지금까지의 기본값. 이미 그린 도면이 안 바뀐다 */
      return Math.max(MIN_MULT, 1 + r * (rand() * 2 - 1));
  }
}
