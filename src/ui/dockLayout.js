/**
 * 아래 띠의 높이 — 씬을 16:9 로 남기고 **나머지**를 준다.
 * ---------------------------------------------------------------------------
 *  CSS 로는 안 된다. 씬에 `aspect-[16/9]` 를 주고 씬·띠를 둘 다 `flex-1` 로 두면
 *  플렉스가 비율을 눌러 **반씩 갈라 버린다**(실제로 씬 322 · 띠 323 이 나왔다).
 *  「부모 폭의 9/16 만큼 높이」 를 쓰는 CSS 문법이 없어서, 재서 정한다.
 *
 *  JSX 가 아니라 여기 있는 이유는 **검사가 node 로 직접 부르기 위해서**다.
 * ---------------------------------------------------------------------------
 */

/** 이보다 낮아지면 글자가 잘려 계기판 노릇을 못 한다 */
export const MIN_H = 190;
/** 이보다 높아지면 계기판이 도면을 밀어낸다 — 남는 몫은 씬이 갖는다 */
export const MAX_H = 340;
export const SCENE_RATIO = 16 / 9;

export const dockHeight = (w, h) =>
  Math.round(Math.min(MAX_H, Math.max(MIN_H, (h ?? 0) - (w ?? 0) / SCENE_RATIO)));
