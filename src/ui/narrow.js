/**
 * 좁은 화면 — **패널이 도면을 이기기 시작하는 지점**.
 * ---------------------------------------------------------------------------
 *  왼쪽 라이브러리와 오른쪽 속성 패널은 합쳐서 최소 412px 을 가져간다. 자리가
 *  1000px 이면 도면에 588 이 남는데, 여기서 더 좁아지면 도면이 패널보다 작아져
 *  「편집기」 라고 부를 수가 없다. 그 아래로는 패널을 **서랍으로 접는다**.
 *
 *  ── px 을 어디서 재는지가 중요하다 ──────────────────────────────────────
 *  화면 배율(core/uiScale.js)은 루트에 CSS `zoom` 으로 걸린다. 그런데
 *
 *      미디어 쿼리 `(max-width: 1024px)`  → 배율을 **무시한다**
 *      `100vw`                            → 배율을 **무시한다**
 *      `offsetWidth` · `%`                → 배율을 **반영한다**
 *
 *  1600px 창을 배율 2 로 보면 실제 자리는 800px 인데 미디어 쿼리는 여전히
 *  1600 이라고 답한다(재서 확인했다). 그래서 **미디어 쿼리를 쓸 수 없다** —
 *  자리를 직접 재서 이 함수에 넣는다. 같은 이유로 패널 폭도 `vw` 가 아니라
 *  `%` 로 준다.
 *
 *  ── 높이를 `vh` 로 막아 둔 자리들 ───────────────────────────────────────
 *  `vh` 도 같은 함정이다. 배율 2 에서 `max-h-[88vh]` 는 화면의 **176%** 가 되어
 *  대화상자 아래쪽 단추에 손이 안 닿는다. `100dvh` 도, `position:fixed` 에
 *  `height:100%` 도 안 통한다(셋 다 재 봤다). 되는 것은 **배율로 되나누는 것**
 *  하나다 — 그래서 store 가 `--z` 를 같이 내놓고, 쓰는 쪽은 이렇게 적는다.
 *
 *      max-h-[calc(88vh/var(--z,1))]
 *
 *  기본값 1 을 꼭 넣는다. 배율이 1 일 때는 store 가 `--z` 를 안 걸 수도 있는데,
 *  기본값이 없으면 calc 이 통째로 무효가 되어 **상한이 사라진다**.
 * ---------------------------------------------------------------------------
 */

/** 이 폭(자리의 실제 px) 아래로는 패널을 서랍으로 접는다 */
export const NARROW_AT = 1000;

/**
 * 아직 못 쟀으면(0) **넓은 것으로 본다.**
 *  처음 한 틱은 0 이 나오는데, 그때 좁다고 답하면 넓은 화면에서도 서랍이
 *  잠깐 번쩍인다. 넓다고 답하면 최악이 「한 틱 늦게 접힌다」 뿐이다.
 */
export const isNarrow = (w) => Number.isFinite(w) && w > 0 && w < NARROW_AT;

/**
 * 패널이 어떤 꼴로 놓이는가 — 'side'(늘 보임) · 'closed'(접힘) · 'open'(덮음).
 *  넓으면 서랍이라는 개념 자체가 없다. 넓어졌는데 'open' 이 남아 있으면
 *  패널이 도면 위에 겹쳐 떠 있게 된다.
 */
export const panelMode = (narrow, open) => (!narrow ? 'side' : open ? 'open' : 'closed');

/**
 * 그 꼴을 CSS 로.
 * ---------------------------------------------------------------------------
 *  넓을 때의 폭은 `clamp(최소, %, 최대)` 다. 최대는 지금까지 쓰던 264·292 그대로라
 *  넓은 화면에서는 **아무것도 안 바뀐다** — 좁아질 때만 같이 줄어든다.
 *    자리 1364px → 264·293(지금과 같다)   ·   자리 1024px → 199·220(합 419, 전엔 556)
 *
 *  `%` 다. `vw` 는 배율을 무시해서 배율 2 에서 패널이 자리의 절반을 먹는다.
 *
 *  서랍은 `absolute` 로 도면을 **덮는다**. 밀어내는 쪽(자리를 차지하는 쪽)은
 *  안 골랐다 — 그러면 도면이 다시 좁아져서 접은 보람이 없다.
 */
export const PANEL_CLASS = {
  lib: {
    side: 'w-[clamp(196px,19.4%,264px)] shrink-0',
    closed: 'hidden',
    open: 'absolute inset-y-0 left-0 z-30 w-[min(264px,82%)] shadow-2xl',
  },
  insp: {
    side: 'w-[clamp(216px,21.5%,292px)] shrink-0',
    closed: 'hidden',
    open: 'absolute inset-y-0 right-0 z-30 w-[min(292px,82%)] shadow-2xl',
  },
};

/** 못 보던 값이 와도 늘 보이는 쪽으로 — 패널이 사라지는 것이 제일 나쁘다 */
export const panelClass = (which, mode) =>
  PANEL_CLASS[which]?.[mode] ?? PANEL_CLASS[which]?.side ?? '';
